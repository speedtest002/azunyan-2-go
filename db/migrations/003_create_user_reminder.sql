CREATE TABLE IF NOT EXISTS USER_REMINDER (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID     NUMBER(20,0) NOT NULL,
    GUILD_ID    NUMBER(20,0),-- NULL if DM
    CHANNEL_ID  NUMBER(20,0) NOT NULL,
    CONTENT     VARCHAR2(2000) NOT NULL,
    DUE_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    STATUS      VARCHAR2(16) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CLAIMED_AT  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT CHK_USER_REMINDER_STATUS CHECK (STATUS IN ('PENDING','PROCESSING','SENT','FAILED','CANCELLED'))
);

CREATE INDEX IF NOT EXISTS IDX_USER_REMINDER_DUE  ON USER_REMINDER (STATUS, DUE_AT);
CREATE INDEX IF NOT EXISTS IDX_USER_REMINDER_USER ON USER_REMINDER (USER_ID, STATUS);

CREATE TABLE IF NOT EXISTS USER_REMINDER_PING (
    REMINDER_ID NUMBER NOT NULL,
    USER_ID     NUMBER(20,0) NOT NULL,
    CONSTRAINT PK_USER_REMINDER_PING PRIMARY KEY (REMINDER_ID, USER_ID),
    CONSTRAINT FK_USER_REMINDER_PING_REMINDER
        FOREIGN KEY (REMINDER_ID) REFERENCES USER_REMINDER(ID) ON DELETE CASCADE
);
